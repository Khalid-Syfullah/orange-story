#!/usr/bin/env node
/**
 * The framing report (`npm run framing`): how large every figure is on screen, scene by scene, at
 * every camera key, on a laptop (1440 x 900) and on a phone (390 x 844); where its head and hands
 * land; whether it runs into a text slot (`SLOT_AREAS`) while words are up; whether any move between
 * keys brings a figure too near the camera (the near plane cuts it) or makes it jump; how many
 * pixels each figure plate needs; and, once the framing table exists (`src/scroll/framing.ts`),
 * whether every target in it is met.
 *
 *   npm run framing                    print it and save test-results/framing/report.md
 *   npm run framing -- --save after    save it as test-results/framing/after.md instead
 *   npm run framing -- --quiet         save only
 *
 * Figures stand at their manifest places (their rest pose): the scenes' choreography (a figure
 * rising into view, walking in, sinking away) moves them from there. Shares are of the stage height
 * (or width); "visible" is the part inside the stage; boxes are the painting's visible (alpha) box.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import {
  beatsBetween,
  cameraFor,
  figureBoxes,
  imagePoint,
  loadStory,
  NEAR,
  NEAR_MARGIN,
  POP_STEP,
  projectBox,
  projectFraction,
  resolutionNeeds,
  ROOT,
  sceneFigures,
  slotOverlap,
  sourceSize,
  sizeWithLong,
  VIEWPORTS,
} from "./framing/core.mjs";

const args = process.argv.slice(2);
const saveIndex = args.indexOf("--save");
const name = saveIndex >= 0 ? args[saveIndex + 1] : "report";
const quiet = args.includes("--quiet");
const OUT = path.join(ROOT, "test-results/framing", `${name}.md`);

const pct = (v) => `${Math.round(v * 100)}%`;
const at2 = (f) => (f ? `${Math.round(f.x * 100)}, ${Math.round(f.y * 100)}` : "behind");
/** Names of points that are about a figure's hands (and what they hold). */
const HAND_POINTS = new Set(["orange", "grip", "fingertips", "fingertip", "knife-tip", "plan", "spout", "shears-tip"]);

function table(head, rows) {
  const line = (cells) => `| ${cells.join(" | ")} |`;
  return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n");
}

function heads(s, entry, pose, viewport) {
  const rig = entry.rig;
  if (!rig) return "";
  const figures = rig.figures?.length ? rig.figures : [rig];
  return figures
    .filter((f) => f.head)
    .map((f) => at2(projectFraction(s, pose, imagePoint(s, entry, [(f.head[0] + f.head[2]) / 2, (f.head[1] + f.head[3]) / 2]), viewport)))
    .join("; ");
}

function hands(s, entry, pose, viewport) {
  return Object.entries(entry.points ?? {})
    .filter(([n]) => HAND_POINTS.has(n))
    .map(([n, uv]) => `${n} ${at2(projectFraction(s, pose, imagePoint(s, entry, uv), viewport))}`)
    .join("; ");
}

async function main() {
  const s = await loadStory();
  const { CAMERA, SCENES } = s.script;
  const boxes = await figureBoxes(s.art.PLATES);
  const cam = cameraFor(s);
  const out = [];
  out.push(`# Framing report (${name})`);
  out.push("");
  out.push(`Generated by \`npm run framing\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC. Laptop ${VIEWPORTS.desktop.width} x ${VIEWPORTS.desktop.height}, phone ${VIEWPORTS.phone.width} x ${VIEWPORTS.phone.height} (the camera fitted to its shape, with the keys' tall-screen pan). Figures stand at their manifest places (their rest pose); shares are of the stage height or width, \`vis\` the part inside the stage. Heads and hands are (x, y) in percent of the stage from its top left. Text: the share of a slot's area the figure's box covers while that slot's words are up.`);
  out.push("");

  // Boxes in the manifest against the files.
  const stale = [...boxes].filter(([id, box]) => {
    const own = s.art.plateEntry(id).box;
    return !own || own.some((v, i) => Math.abs(v - box[i]) > 0.003);
  });
  if (stale.length) {
    out.push(`Visible boxes measured from the files (the manifest ${stale.length === boxes.size ? "has none yet" : `differs for ${stale.map(([id]) => `\`${id}\``).join(", ")}`}).`);
    out.push("");
  }

  // 1. Targets: every row of the framing table, at the key that films it.
  const targets = (s.script.FRAMED ?? []).map((f) => ({ id: f.framing, at: f.at, ...s.framing.FRAMING[f.framing] }));
  if (targets.length) {
    out.push("## Targets");
    out.push("");
    out.push("Each row of the framing table (`src/scroll/framing.ts`) at the camera key that films it. `top` is where the top of the box sits, from the top of the stage. Position: the box's centre (x, y), in percent of the stage.");
    out.push("");
    const rows = [];
    let met = 0;
    for (const t of targets) {
      const cells = [`${t.scene} (${t.at.toFixed(4)})`, t.subject, t.measure];
      let ok = true;
      for (const viewport of [VIEWPORTS.desktop, VIEWPORTS.phone]) {
        const placement = viewport.stacked ? t.phone : t.desktop;
        if (!placement) {
          cells.push("-", "-");
          continue;
        }
        const range = placement.range;
        const pose = cam.pose(t.at, viewport);
        const seen = projectBox(s, pose, t.box(), viewport);
        const value = t.measure === "width" ? seen.widthShare : t.measure === "top" ? seen.rect.top / viewport.height : seen.heightShare;
        const inside = seen.depth > 0 && value >= range[0] - 0.005 && value <= range[1] + 0.005;
        ok &&= inside;
        const centre = `${Math.round(((seen.rect.left + seen.rect.right) / 2 / viewport.width) * 100)}, ${Math.round(((seen.rect.top + seen.rect.bottom) / 2 / viewport.height) * 100)}`;
        cells.push(`${pct(range[0])} to ${pct(range[1])}`, `${pct(value)} at ${centre}${inside ? "" : " (off)"}`);
      }
      if (ok) met++;
      cells.push(ok ? "met" : "NOT MET", t.note ?? "");
      rows.push(cells);
    }
    out.push(table(["Scene (key)", "Subject", "Share of", "Laptop target", "Laptop", "Phone target", "Phone", "Status", "Notes"], rows));
    out.push("");
    out.push(`${met} of ${targets.length} targets met.`);
    out.push("");
  }

  // 2. Every key.
  out.push("## Every camera key");
  out.push("");
  for (const scene of SCENES) {
    const figures = sceneFigures(s, scene.id);
    const keys = CAMERA.map((k, i) => ({ k, next: CAMERA[i + 1] })).filter(({ k }) => k.scene === scene.id);
    if (!figures.length || !keys.length) continue;
    out.push(`### ${scene.number}. ${scene.id}`);
    out.push("");
    for (const viewport of [VIEWPORTS.desktop, VIEWPORTS.phone]) {
      const rows = [];
      for (const { k, next } of keys) {
        const pose = cam.pose(k.at, viewport);
        const beats = beatsBetween(s, k.at, next ? next.at : Math.min(1, k.at + 0.01));
        for (const entry of figures) {
          const box = s.framing.plateBoxOf(entry, boxes.get(entry.id));
          const seen = projectBox(s, pose, box, viewport);
          const text = beats
            .map((b) => [b.slot, slotOverlap(seen.clip, s.haze.SLOT_AREAS[b.slot][viewport.stacked ? "stacked" : "wide"], viewport)])
            .filter(([, v]) => v > 0.005)
            .map(([slot, v]) => `${slot} ${pct(v)}`);
          const unique = [...new Set(text)];
          rows.push([
            `${k.at.toFixed(4)} ${k.move}`,
            `\`${entry.id}\``,
            seen.onScreen ? `${pct(seen.heightShare)} (vis ${pct(seen.visibleHeightShare)})` : seen.depth <= 0 ? "behind" : "off",
            seen.onScreen ? `${pct(seen.widthShare)} (vis ${pct(seen.visibleWidthShare)})` : "",
            seen.onScreen ? heads(s, entry, pose, viewport) : "",
            seen.onScreen ? hands(s, entry, pose, viewport) : "",
            unique.join("; ") || "clear",
          ]);
        }
      }
      out.push(`${viewport.name === "desktop" ? "Laptop" : "Phone"}:`);
      out.push("");
      out.push(table(["Key", "Plate", "Height", "Width", "Heads", "Hands", "Text"], rows));
      out.push("");
    }
  }

  // 3. Moves.
  out.push("## Moves between keys");
  out.push("");
  out.push(`Each move sampled 48 times on both stages: the nearest any figure on screen comes to the camera (the near plane is ${NEAR}; nearer than ${NEAR_MARGIN} is flagged), the largest change in a figure's height on screen between two samples, and whether any change is a pop: a step over ${pct(POP_STEP)} of the stage height and three times the steps either side of it (a cut in a smooth move). A reframe happens under a full cover and is not checked.`);
  out.push("");
  const moveRows = [];
  let flagged = 0;
  for (let i = 0; i + 1 < CAMERA.length; i++) {
    const a = CAMERA[i];
    const b = CAMERA[i + 1];
    let nearest = Infinity;
    let nearestId = "";
    let step = 0;
    let stepId = "";
    let pop = "";
    for (const viewport of [VIEWPORTS.desktop, VIEWPORTS.phone]) {
      const series = new Map();
      for (let n = 0; n <= 48; n++) {
        const p = a.at + ((b.at - a.at) * n) / 48;
        const sceneId = s.helpers.currentScene(p).id;
        const pose = cam.pose(p, viewport);
        for (const entry of sceneFigures(s, sceneId)) {
          const seen = projectBox(s, pose, s.framing.plateBoxOf(entry, boxes.get(entry.id)), viewport);
          const lateral = seen.rect.right > 0 && seen.rect.left < viewport.width && seen.rect.bottom > 0 && seen.rect.top < viewport.height;
          if ((seen.onScreen || (lateral && seen.depth <= NEAR)) && seen.depth < nearest) {
            nearest = seen.depth;
            nearestId = `${entry.id} (${viewport.name})`;
          }
          if (!series.has(entry.id)) series.set(entry.id, []);
          series.get(entry.id).push(seen.onScreen && seen.depth > NEAR_MARGIN ? seen.heightShare : Number.NaN);
        }
      }
      if (a.move === "reframe") continue;
      for (const [id, values] of series) {
        const steps = values.slice(1).map((v, k) => Math.abs(v - values[k]));
        steps.forEach((d, k) => {
          if (!Number.isFinite(d)) return;
          if (d > step) {
            step = d;
            stepId = `${id} (${viewport.name})`;
          }
          const around = Math.max(Number.isFinite(steps[k - 1]) ? steps[k - 1] : 0, Number.isFinite(steps[k + 1]) ? steps[k + 1] : 0);
          if (d > POP_STEP && d > 3 * around) pop = `${id} (${viewport.name})`;
        });
      }
    }
    if (nearest === Infinity) continue;
    const flags = [];
    if (nearest < NEAR) flags.push("CLIPS");
    else if (nearest < NEAR_MARGIN) flags.push("close");
    if (pop) flags.push(`pop: ${pop}`);
    if (flags.length) flagged++;
    moveRows.push([`${a.scene} ${a.at.toFixed(4)} to ${b.at.toFixed(4)}`, a.move, `${nearest.toFixed(2)} (${nearestId})`, step ? `${pct(step)} (${stepId})` : "0%", flags.join(", ") || "ok"]);
  }
  out.push(table(["Move", "Kind", "Nearest figure", "Largest step", "Check"], moveRows));
  out.push("");
  out.push(`${flagged} of ${moveRows.length} moves with figures flagged.`);
  out.push("");

  // 4. Pixels.
  out.push("## Pixels");
  out.push("");
  out.push("The tallest each figure plate is drawn (its whole image, CSS pixels) on either stage, and the long side its image needs on a 2x display (capped at 2560). The stage itself renders at a pixel ratio of at most 1.5 (1.25 on a phone), so this leaves headroom.");
  out.push("");
  const needs = resolutionNeeds(s, boxes);
  const pixelRows = [];
  for (const n of needs) {
    const src = await sourceSize(n.id);
    const have = Math.max(...n.size);
    const verdict = n.neededLong <= have ? "enough" : src && Math.max(...src) >= n.neededLong ? `raise to ${sizeWithLong(n.size, n.neededLong).join(" x ")} (the painting has it)` : `regenerate at ${sizeWithLong(n.size, n.neededLong).join(" x ")}`;
    pixelRows.push([`\`${n.id}\``, n.size.join(" x "), src ? src.join(" x ") : "not here", `${n.drawnPx} px (${n.where})`, String(n.neededLong), verdict]);
  }
  out.push(table(["Plate", "Image", "Painting", "Drawn up to", "Needs (long side)", "Verdict"], pixelRows));
  out.push("");

  cam.kill();
  const text = `${out.join("\n")}\n`;
  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, text);
  if (!quiet) console.log(text);
  console.log(`Saved ${path.relative(ROOT, OUT)}.`);
}

await main();
