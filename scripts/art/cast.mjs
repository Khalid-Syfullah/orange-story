/** Every character plate id, in cast order. */
export const CHARACTER_PLATES = CAST.flatMap((c) => Object.keys(c.plates));

/** The character that appears in a plate. */
export function castFor(plateId) {
  return CAST.find((c) => plateId in c.plates) ?? null;
}

/** Whether a plate shows a character (the texture guard holds these to a painted standard). */
export const isFigurePlate = (plateId) => CHARACTER_PLATES.includes(plateId);
